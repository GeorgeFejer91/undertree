const TEX_ENGINES = new Set(["pdflatex", "lualatex", "xelatex"]);

function stripTexComments(content) {
  return content.split(/\r?\n/).map((line) => {
    for (let index = 0; index < line.length; index += 1) {
      if (line[index] !== "%") continue;
      let escapes = 0;
      for (let cursor = index - 1; cursor >= 0 && line[cursor] === "\\"; cursor -= 1) escapes += 1;
      if (escapes % 2 === 0) return line.slice(0, index);
    }
    return line;
  }).join("\n");
}

function requiresUnicodeEngine(content) {
  const packagePattern = /\\(?:usepackage|RequirePackage)(?:\s*\[[^\]]*\])?\s*\{([^}]*)\}/gi;
  let match;
  while ((match = packagePattern.exec(content))) {
    if (/(?:^|,)\s*(?:fontspec|unicode-math)\s*(?:,|$)/i.test(match[1])) return true;
  }
  return /\\(?:setmainfont|setsansfont|setmonofont|newfontfamily|addfontfeatures|directlua)\b/.test(content);
}

export function texEngineDirective(content) {
  const header = content.split(/\r?\n/, 50).join("\n");
  const match = header.match(/^\s*%\s*!\s*TeX\s+(?:TS-)?program\s*=\s*((?:pdf|lua|xe)latex)\s*$/im);
  const engine = match?.[1]?.toLowerCase() || "";
  return TEX_ENGINES.has(engine) ? engine : "";
}

export function inferredTexEngine(content) {
  const source = stripTexComments(content);
  if (!requiresUnicodeEngine(source)) return "";

  // UnderTree's generated layout target is always LuaLaTeX. This also repairs
  // routing for layout files created before the engine directive was emitted.
  if (/^\s*%\s*Generated by UnderTree Layout\b/im.test(content)) return "lualatex";

  // A conventional iftex branch intentionally supports pdfLaTeX. Ignore the
  // Unicode-only half before deciding whether the rest of the file needs LuaTeX.
  const outsidePdfTexFallback = source.replace(/\\ifPDFTeX\b[\s\S]*?\\else\b[\s\S]*?\\fi\b/g, "");
  return requiresUnicodeEngine(outsidePdfTexFallback) ? "lualatex" : "";
}

export function texEngineForContent(content, fallback = "pdflatex") {
  return texEngineDirective(content) || inferredTexEngine(content) || fallback;
}
