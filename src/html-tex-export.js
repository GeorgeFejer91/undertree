function texEscape(value) {
  return String(value || "")
    .replaceAll("\\", "\\textbackslash{}")
    .replaceAll("{", "\\{")
    .replaceAll("}", "\\}")
    .replaceAll("#", "\\#")
    .replaceAll("$", "\\$")
    .replaceAll("%", "\\%")
    .replaceAll("&", "\\&")
    .replaceAll("_", "\\_")
    .replaceAll("^", "\\textasciicircum{}")
    .replaceAll("~", "\\textasciitilde{}");
}

function parseColor(value) {
  const match = String(value || "").match(/rgba?\(\s*(\d+(?:\.\d+)?)\s*,\s*(\d+(?:\.\d+)?)\s*,\s*(\d+(?:\.\d+)?)(?:\s*,\s*([\d.]+))?\s*\)/i);
  if (!match) return null;
  const alpha = match[4] === undefined ? 1 : Number(match[4]);
  if (alpha <= 0.001) return null;
  return { rgb: match.slice(1, 4).map((item) => Math.round(Number(item))), alpha };
}

function colorName(registry, value) {
  const parsed = parseColor(value);
  if (!parsed) return null;
  const key = parsed.rgb.join("-");
  if (!registry.has(key)) registry.set(key, `utcolor${registry.size + 1}`);
  return { name: registry.get(key), ...parsed };
}

function point(rect) {
  return `($(current page.north west)+(${rect.xMm}mm,-${rect.yMm}mm)$)`;
}

function textPoint(item) {
  const cssInkOffsetMm = Number(item.fontSizePx || 12) * 0.5 * 25.4 / 96;
  return `($(current page.north west)+(${item.rect.xMm}mm,-${(item.rect.yMm + cssInkOffsetMm).toFixed(3)}mm)$)`;
}

function texLineText(value) {
  const source = String(value || "");
  const leadingSpace = /^\s/.test(source) ? "\\ " : "";
  return `${leadingSpace}${texEscape(source.replace(/\s+/g, " ").trim())}`;
}

export function generateLuaLatex(manifest, { sourceHash, profileVersion, pretextVersion, webkitVersion, sourcePath = "", browserPdfSha256 = "" } = {}) {
  const colors = new Map();
  for (const object of manifest.objects || []) {
    colorName(colors, object.backgroundColor);
    colorName(colors, object.borderColor);
    colorName(colors, object.color);
  }
  for (const line of manifest.lines || []) colorName(colors, line.color);

  const definitions = [...colors.entries()].map(([rgb, name]) => `\\definecolor{${name}}{RGB}{${rgb.replaceAll("-", ",")}}`).join("\n");
  const pageWidthMm = Number(manifest.pdfPageSizePt?.width || 595.2756) * 25.4 / 72;
  const pageHeightMm = Number(manifest.pdfPageSizePt?.height || 841.8898) * 25.4 / 72;
  const pages = manifest.pages || [];
  const reconstructedBody = pages.map((page) => {
    const pageNumber = page.number;
    const boxes = (manifest.objects || []).filter((item) => item.page === pageNumber).map((item) => {
      const fill = colorName(colors, item.backgroundColor);
      const border = item.borderWidthPx > 0 ? colorName(colors, item.borderColor) : null;
      if (!fill && !border) return "";
      const options = [];
      if (fill) options.push(`fill=${fill.name}`, fill.alpha < 1 ? `fill opacity=${fill.alpha}` : "");
      if (border) options.push(`draw=${border.name}`, `line width=${(item.borderWidthPx * 0.75).toFixed(3)}pt`, border.alpha < 1 ? `draw opacity=${border.alpha}` : "");
      else options.push("draw=none");
      if (item.borderRadiusPx > 0) options.push(`rounded corners=${(item.borderRadiusPx * 0.75).toFixed(3)}pt`);
      return `\\path[${options.filter(Boolean).join(",")}] ${point(item.rect)} rectangle ++(${item.rect.widthMm}mm,-${item.rect.heightMm}mm); % ${item.dataUtId}`;
    }).filter(Boolean);
    const images = (manifest.images || []).filter((item) => item.page === pageNumber).map((item) => {
      const asset = item.texSrc || item.src;
      const trim = /UniKonstanz_Logo_Optimum_SW\.pdf$/i.test(asset) ? ",trim=212bp 212bp 212bp 142bp,clip" : "";
      return `\\node[anchor=north west,inner sep=0,outer sep=0] at ${point(item.rect)} {\\includegraphics[width=${item.rect.widthMm}mm,height=${item.rect.heightMm}mm,keepaspectratio${trim}]{\\detokenize{${asset}}}}; % ${item.dataUtId}`;
    });
    const lines = (manifest.lines || []).filter((item) => item.page === pageNumber).map((item) => {
      const color = colorName(colors, item.color);
      const sizePt = Math.max(1, Number(item.fontSizePx || 12) * 0.75);
      const weight = Number.parseInt(item.fontWeight, 10) >= 600 || /bold/i.test(item.fontWeight) ? "\\bfseries" : "";
      const shape = item.fontStyle === "italic" ? "\\itshape" : "";
      const options = ["anchor=north west", "inner sep=0", "outer sep=0", `text=${color?.name || "black"}`, `font=\\fontsize{${sizePt.toFixed(3)}}{${(sizePt * 1.15).toFixed(3)}}\\selectfont${weight}${shape}`];
      let content = texLineText(item.text);
      if (item.link) content = `\\href{${texEscape(item.link)}}{${content}}`;
      return `\\node[${options.join(",")}] at ${textPoint(item)} {${content}}; % ${item.dataUtId}`;
    });
    return `\\begin{tikzpicture}[remember picture,overlay]\n${[...boxes, ...images, ...lines].join("\n")}\n\\end{tikzpicture}\n\\null${pageNumber < pages.length ? "\\newpage" : ""}`;
  }).join("\n");
  return `% GENERATED BY UNDERTREE — HTML IS THE SOLE SOURCE OF TRUTH.
% Source: ${sourcePath}
% Canonical HTML SHA-256: ${sourceHash}
% Print profile: ${profileVersion}; Pretext: ${pretextVersion}; WebKitGTK: ${webkitVersion}
% Canonical browser PDF SHA-256: ${browserPdfSha256 || "not recorded"}
% The browser PDF remains a separate build artifact; this file reconstructs the manifest as editable TikZ/text.
% Later HTML exports intentionally overwrite this file.
\\documentclass[a4paper]{article}
\\usepackage[paperwidth=${pageWidthMm.toFixed(5)}mm,paperheight=${pageHeightMm.toFixed(5)}mm,margin=0mm]{geometry}
\\usepackage{fontspec}
\\usepackage{graphicx}
\\usepackage{xcolor}
\\usepackage{tikz}
\\usetikzlibrary{calc}
\\usepackage[hidelinks]{hyperref}
\\IfFontExistsTF{Noto Sans}{\\setmainfont{Noto Sans}}{\\setmainfont{TeX Gyre Heros}}
\\pagestyle{empty}
\\setlength{\\parindent}{0pt}
${definitions}
\\begin{document}
${reconstructedBody}
\\end{document}
`;
}

export { texEscape };
